#!/usr/bin/env bash
# Build genuine GNU userland as RV64GC THX2, without modifying the live root until verified.
set -Eeuo pipefail
PROJECT="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/../.." && pwd)"
ROOT="$PROJECT/.thistle.base"
INSTALL=0
REUSE=0
while (($#)); do
  case "$1" in
    --root) ROOT="$2"; shift 2 ;;
    --install) INSTALL=1; shift ;;
    --from-staged) REUSE=1; shift ;;
    -h|--help) echo 'Usage: bash scripts/userland/build-gnu-prebuilts.sh [--root PATH] [--install] [--from-staged]'; exit 0 ;;
    *) printf 'Unknown argument: %s\n' "$1" >&2; exit 2 ;;
  esac
done
TARGET=riscv64-unknown-linux-musl
CROSS_PREFIX="${MIKUOS_CROSS_PREFIX:-riscv64-unknown-linux-musl-}"
CC="${CROSS_PREFIX}gcc"
AR="${CROSS_PREFIX}ar"
RANLIB="${CROSS_PREFIX}ranlib"
for tool in bun install cp; do
  command -v "$tool" >/dev/null || { printf 'Missing tool: %s\n' "$tool" >&2; exit 2; }
done

[[ -f "$PROJECT/src/tool/elf2thx.ts" && -f "$PROJECT/dist/teto/teto.wasm" ]] || {
  echo 'Build mikuOS before compiling the GNU userland' >&2; exit 2;
}
[[ -d "$ROOT" ]] || { printf 'Missing guest root: %s\n' "$ROOT" >&2; exit 2; }
WORK="$(mktemp -d "${TMPDIR:-/tmp}/mikuos-gnu.XXXXXXXX")"
trap 'rm -rf -- "$WORK"' EXIT

# Preserve completed native binaries before running guest smoke tests. A test
# failure must never discard a lengthy, successful cross-compilation.
OUT="$PROJECT/.rebuild-userland/gnu-prebuilts"
mkdir -p "$WORK/prebuilt" "$OUT/licenses/coreutils" "$OUT/licenses/bash"

if (( ! REUSE )); then
  for tool in curl tar sha256sum make readelf "$CC" "$AR" "$RANLIB"; do
    command -v "$tool" >/dev/null || {
      printf 'Missing build tool: %s\n' "$tool" >&2
      exit 2
    }
  done
  [[ "$("$CC" -dumpmachine)" == *riscv64*musl* ]] || {
    echo 'Requires the RV64 musl toolchain' >&2
    exit 2
  }
fetch() {
  curl --fail --location --retry 3 --silent --show-error "$1" -o "$3"
  printf '%s  %s\n' "$2" "$3" | sha256sum --check --status || {
    printf 'Invalid GNU source checksum: %s\n' "$1" >&2; return 1;
  }
}
fetch https://ftp.gnu.org/gnu/coreutils/coreutils-9.12.tar.xz \
  a480198559733e9b3da999e90543ac6f888a2caa544d8d664c5a1f17e528e210 "$WORK/coreutils.tar.xz"
fetch https://ftp.gnu.org/gnu/bash/bash-5.3.tar.gz \
  0d5cd86965f869a26cf64f4b71be7b96f90a3ba8b3d74e27e8e9d9d5550f31ba "$WORK/bash.tar.gz"
tar -xJf "$WORK/coreutils.tar.xz" -C "$WORK"
tar -xzf "$WORK/bash.tar.gz" -C "$WORK"
JOBS="${MIKUOS_BUILD_JOBS:-2}"
[[ "$JOBS" =~ ^[1-9][0-9]*$ ]] || { echo 'Invalid build job count' >&2; exit 2; }
mkdir -p "$WORK/core-build" "$WORK/bash-build" "$WORK/prebuilt"
(
  cd "$WORK/core-build"
  CC="$CC" AR="$AR" RANLIB="$RANLIB" CFLAGS=-O2 LDFLAGS=-static \
    "$WORK/coreutils-9.12/configure" --host="$TARGET" --prefix=/usr --disable-nls
  # The Gnulib wrapper headers (locale.h, string.h, error.h and others)
  # are generated by the top-level 'all' target. Building individual src/*
  # targets directly bypasses those prerequisites and leaves symbols such as
  # SETLOCALE_NULL_MAX, setlocale_null_r and streq undeclared.
  # Build the full upstream dependency graph, then package only head/dd/od.
  make --jobs="$JOBS" all
)
(
  cd "$WORK/bash-build"
  CC="$CC" AR="$AR" RANLIB="$RANLIB" CFLAGS=-O2 LDFLAGS=-static \
    "$WORK/bash-5.3/configure" --host="$TARGET" --prefix=/usr \
      --disable-nls --without-bash-malloc
  make --jobs="$JOBS" bash
)
for name in head dd od bash; do
  case "$name" in
    bash) elf="$WORK/bash-build/bash" ;;
    *) elf="$WORK/core-build/src/$name" ;;
  esac
  [[ -s "$elf" ]] || { printf 'Missing GNU ELF: %s\n' "$elf" >&2; exit 1; }
  readelf -h "$elf" | grep -Eq 'Machine:[[:space:]]+RISC-V' || {
    printf 'Not a RISC-V ELF: %s\n' "$elf" >&2; exit 1;
  }
  if readelf -l "$elf" | grep -q 'INTERP'; then
    printf 'Refusing dynamically linked GNU %s\n' "$name" >&2; exit 1
  fi
  bun "$PROJECT/src/tool/elf2thx.ts" "$elf" "$WORK/prebuilt/$name"
  [[ "$(head -c 4 "$WORK/prebuilt/$name")" == THX2 ]] || {
    printf 'Invalid THX2 format: %s\n' "$name" >&2; exit 1
  }
done

  for name in head dd od bash; do
    install -m 0755 "$WORK/prebuilt/$name" "$OUT/$name.39"
  done
  install -m 0644 "$WORK/coreutils-9.12/COPYING" "$OUT/licenses/coreutils/COPYING"
  install -m 0644 "$WORK/bash-5.3/COPYING" "$OUT/licenses/bash/COPYING"
  echo "Built GNU THX2 binaries preserved in $OUT"
else
  echo "Reusing existing GNU THX2 binaries from $OUT (no recompilation)"
  for name in head dd od bash; do
    [[ -s "$OUT/$name.39" ]] || {
      echo "Missing staged binary: $OUT/$name.39" >&2
      exit 2
    }
    [[ "$(head -c 4 "$OUT/$name.39")" == THX2 ]] || {
      echo "Invalid staged THX2 binary: $OUT/$name.39" >&2
      exit 2
    }
    cp -- "$OUT/$name.39" "$WORK/prebuilt/$name"
  done
  for licence in coreutils bash; do
    [[ -s "$OUT/licenses/$licence/COPYING" ]] || {
      echo "Missing staged $licence licence" >&2
      exit 2
    }
  done
fi

candidate="$WORK/root"
mkdir -p "$candidate/bin"
cp -a -- "$ROOT/." "$candidate/"
# Git does not track empty /tmp or /root directories. The synthetic guest
# root must provide them before dd can create its test files.
install -d -m 1777 "$candidate/tmp"
install -d -m 0700 "$candidate/root"
for name in head dd od bash; do
  install -m 0755 "$WORK/prebuilt/$name" "$candidate/bin/$name"
done
rm -f -- "$candidate/usr/libexec/mikuos/builtin/head"
for spec in \
  "printf 'one\\ntwo\\n' | head -n 1" \
  "printf 'ABC' >/tmp/data; dd if=/tmp/data of=/tmp/copy bs=1 count=3; od -An -tx1 /tmp/copy" \
  "bash -c 'printf bash-ready'"; do
  bash "$PROJECT/scripts/userland/dual-kernel-test.sh" --root "$candidate" -- "$spec"
done
printf 'GNU THX2 guest smoke tests passed; staged binaries: %s\n' "$OUT"
if ((INSTALL)); then
  backup="$PROJECT/.rebuild-userland/pre-install-$(date -u +%Y%m%dT%H%M%SZ)"
  mkdir -p "$backup" "$ROOT/bin" "$ROOT/usr/share/licenses/coreutils" "$ROOT/usr/share/licenses/bash"
  for name in head dd od bash; do
    if [[ -e "$ROOT/bin/$name" || -L "$ROOT/bin/$name" ]]; then
      cp -a -- "$ROOT/bin/$name" "$backup/$name"
    fi
  done
  for name in head dd od bash; do
    install -m 0755 "$WORK/prebuilt/$name" "$ROOT/bin/$name"
  done
  install -m 0644 "$OUT/licenses/coreutils/COPYING" "$ROOT/usr/share/licenses/coreutils/COPYING"
  install -m 0644 "$OUT/licenses/bash/COPYING" "$ROOT/usr/share/licenses/bash/COPYING"
  rm -f -- "$ROOT/usr/libexec/mikuos/builtin/head"
  # Browser root packaging is driven by this manifest, not directory scans.
  # Keep it in sync with the six installed files and their licence folders.
  bun "$PROJECT/scripts/userland/sync-gnu-prebuilt-meta.mts" "$ROOT"
  printf 'Installed GNU binaries into %s/bin; originals backed up in %s\n' "$ROOT" "$backup"
fi
